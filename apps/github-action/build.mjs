// Bundles the action into one file GitHub runs directly (dist/index.mjs, committed). CI rebuilds it and fails if the
// committed bundle differs, so what runs is always what was reviewed. It also builds the dependency-free CI report
// script for Bitbucket Pipelines and other CIs (scripts/threatline-ci-report.mjs at the repository root, committed,
// readable: not minified). THREATLINE_BUILD_OUT writes both under another directory instead (the bundle-sync test).
import { build } from 'esbuild';
import { join } from 'node:path';

const out = process.env.THREATLINE_BUILD_OUT;
const actionOut = out ? join(out, 'dist/index.mjs') : 'dist/index.mjs';
const scriptOut = out ? join(out, 'scripts/threatline-ci-report.mjs') : '../../scripts/threatline-ci-report.mjs';

await build({
  entryPoints: ['src/main.ts'],
  outfile: actionOut,
  bundle: true,
  platform: 'node',
  target: 'node24',
  format: 'esm',
  legalComments: 'none',
  logLevel: 'warning',
  minify: true,
  banner: { js: "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
});
await build({
  entryPoints: ['src/ci-report-cli.ts'],
  outfile: scriptOut,
  bundle: true,
  platform: 'node',
  target: 'node18',
  format: 'esm',
  legalComments: 'none',
  logLevel: 'warning',
  banner: {
    js: [
      '#!/usr/bin/env node',
      '// Threatline CI report: tells Threatline which requirement tests passed (docs/CI_VERIFICATION.md). Node 18+, no',
      '// dependencies. GENERATED by apps/github-action/build.mjs from apps/github-action/src/ci-report.ts; do not edit.',
      '// Usage: THREATLINE_URL=… THREATLINE_TOKEN=… node threatline-ci-report.mjs --junit "test-results/**/*.xml"',
    ].join('\n'),
  },
});
console.log(`built ${actionOut} and ${scriptOut}`);
