import type { Acceptance, ArchitectureSketch, Requirement, Review, Threat } from '@threatline/shared';
import { count } from '../verdict.js';
import type { DiagramModel } from '../diagram.js';

export interface ThreatModelDto {
  issueKey: string;
  summary: string;
  review: Review;
  /** The work item's newest revision; when it is newer than `review`, the page says it is out of date. */
  latestRevision: number;
  verdict: { state: 'pass' | 'block' | 'warn'; message: string } | null;
  sketch?: ArchitectureSketch;
  /** The data-flow diagram, built from what this page's readers may see (rendered as tables: storage holds no SVG). */
  diagram?: DiagramModel;
  /** The architecture sketch was left out because it rests on sources this page's readers may not open. */
  diagramPartial?: boolean;
  threats: Threat[];
  requirements: Requirement[];
  acceptances: Acceptance[];
  history: Array<{ revision: number; createdAt: string; riskScore: number; status: Review['status'] }>;
  panelUrl: string;
  /** Confluence storage of the human-edited "Owner notes" section, kept across regenerations (RQ-6). */
  ownerNotes: string;
  /** Threats citing sources this page's readers may not be able to open: shown without their text. */
  redactedThreatIds: string[];
}

export const DEFAULT_OWNER_NOTES = '<p>Add your notes here. Threatline keeps this section when it updates the page.</p>';
const OWNER_NOTES = '<h2>Owner notes</h2>';

const STRIDE: Record<Threat['stride'], string> = {
  Spoofing: 'Spoofing',
  Tampering: 'Tampering',
  Repudiation: 'Repudiation',
  InformationDisclosure: 'Information disclosure',
  DenialOfService: 'Denial of service',
  ElevationOfPrivilege: 'Elevation of privilege',
};
const STATUS: Record<Requirement['status'], string> = { Open: 'Open', InProgress: 'In progress', Verified: 'Verified', AcceptedRisk: 'Accepted risk', NotApplicable: 'Not applicable' };
const THREAT_STATE: Record<Threat['state'], string> = { proposed: 'Proposed', accepted: 'Accepted', dismissed: 'Dismissed', needs_human: 'Needs a champion', covered: 'Covered by a more specific threat' };
const VERDICT: Record<'pass' | 'block' | 'warn', string> = { pass: 'Ready for Done', block: 'Blocks Done and merge', warn: 'Warn-only' };

/** Escapes text for Confluence storage (XHTML): every value from Jira, the model or a person goes through this. */
export const esc = (s: string): string => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
const day = (iso: string) => esc(iso.slice(0, 10));
const td = (s: string) => `<td>${s}</td>`;
const th = (s: string) => `<th>${esc(s)}</th>`;
const table = (head: string[], rows: string[][]) =>
  `<table><tbody><tr>${head.map(th).join('')}</tr>${rows.map((r) => `<tr>${r.map(td).join('')}</tr>`).join('')}</tbody></table>`;
const macro = (name: 'info' | 'note' | 'panel', body: string, title?: string) =>
  `<ac:structured-macro ac:name="${name}">${title ? `<ac:parameter ac:name="title">${esc(title)}</ac:parameter>` : ''}<ac:rich-text-body>${body}</ac:rich-text-body></ac:structured-macro>`;
const link = (href: string, text: string) => `<a href="${esc(href)}">${esc(text)}</a>`;

/** RQ-5: the threat-model page, as Confluence storage XHTML. Pure: no I/O, every dynamic value escaped. */
export function renderThreatModel(d: ThreatModelDto): string {
  const redacted = new Set(d.redactedThreatIds);
  const threatOf = new Map(d.threats.map((t) => [t.id, t]));
  const out: string[] = [];

  if (d.latestRevision > d.review.revision)
    out.push(macro('info', `<p>This page shows revision ${d.review.revision}. The work item has revision ${d.latestRevision}, which is still in progress or did not finish. Open the ${link(d.panelUrl, 'Threatline panel')} for the latest state.</p>`, 'Out of date'));

  const open = d.requirements.filter((r) => r.status === 'Open' || r.status === 'InProgress').length;
  const active = d.threats.filter((t) => t.state !== 'dismissed' && t.state !== 'covered');
  out.push('<h2>Summary</h2>');
  out.push(
    macro(
      'panel',
      [
        `<p><strong>${esc(d.issueKey)}</strong>: ${esc(d.summary)}</p>`,
        `<p>Risk score: <strong>${d.review.riskScore}</strong> of 100. Verdict: <strong>${esc(d.verdict ? VERDICT[d.verdict.state] : 'Not computed')}</strong>.</p>`,
        d.verdict && d.verdict.state !== 'pass' ? `<p>${esc(d.verdict.message)}</p>` : '',
        `<p>${count(active.length, 'threat')}, ${count(d.requirements.length, 'requirement')} (${open} open), ${count(d.acceptances.length, 'risk acceptance')}. Revision ${d.review.revision}, reviewed ${day(d.review.updatedAt)}.</p>`,
        `<p>Generated by Threatline from the ${link(d.panelUrl, 'Threatline panel')}. Edit only the Owner notes section; the rest is replaced on each review.</p>`,
      ].join(''),
      'Threatline security review',
    ),
  );

  if (d.diagram && d.diagram.nodes.length > 0) out.push(...renderDiagram(d.diagram, d.diagramPartial === true, d.panelUrl));

  if (d.sketch) {
    const s = d.sketch;
    const list = (xs: string[]) => esc(xs.join(', ') || '—');
    out.push('<h2>Architecture sketch</h2>');
    out.push(
      table(
        ['Part', 'Contents'],
        [
          ['Components', list(s.components)],
          ['Data stores', list(s.dataStores)],
          ['External services', list(s.externalServices)],
          ['Trust boundaries', list(s.trustBoundaries)],
          ['Data flows', esc(s.flows.map((f) => `${f.from} → ${f.to}: ${f.data}`).join('; ') || '—')],
          ['Data classes', list(s.dataClasses)],
          ['Exposure', esc(s.exposure)],
          ['Uses AI', s.llmFeatures ? 'Yes' : 'No'],
        ],
      ),
    );
  }

  out.push('<h2>Threats</h2>');
  out.push(
    d.threats.length === 0
      ? '<p>No threats.</p>'
      : table(
          ['Threat', 'Category', 'Severity', 'Runs agreeing', 'State', 'Standards'],
          d.threats.map((t) => {
            const hidden = redacted.has(t.id);
            const what = hidden
              ? '<em>Comes from sources not everyone who can read this page can open: details in the Threatline panel.</em>'
              : `<strong>${esc(t.plainLanguage || t.title)}</strong><br/>${esc(t.title)}. ${esc(t.scenario)}`;
            const coveredBy = t.coveredBy ? d.threats.find((o) => o.id === t.coveredBy) : undefined;
            const state = `${THREAT_STATE[t.state]}${t.dismissReason ? ` (${t.dismissReason.replace(/_/g, ' ')})` : ''}${coveredBy && !redacted.has(coveredBy.id) ? `: ${coveredBy.title}` : ''}`;
            return [what, esc(STRIDE[t.stride]), esc(t.severity), t.origin === 'baseline' ? 'Rule-based' : `${t.votes} of ${t.samples}`, esc(state), esc(t.mappings.map((m) => m.refId).join(', '))];
          }),
        ),
  );

  out.push('<h2>Security requirements</h2>');
  out.push(
    d.requirements.length === 0
      ? '<p>No requirements.</p>'
      : table(
          ['Requirement', 'Sub-task', 'Severity', 'Status', 'Acceptance criteria', 'ASVS'],
          d.requirements.map((r) => {
            const t = threatOf.get(r.threatId);
            const hidden = redacted.has(r.threatId) || !t;
            const title = hidden ? '<em>Details in the Threatline panel.</em>' : esc(r.title);
            const criteria = hidden ? '' : r.criteria.map((c) => esc(`Given ${c.given}, when ${c.when}, then ${c.then}.`)).join('<br/>');
            return [title, esc(r.subtaskKey ?? '—'), esc(r.severity), esc(STATUS[r.status]), criteria, esc(r.asvsIds.join(', '))];
          }),
        ),
  );

  out.push('<h2>Risk acceptances</h2>');
  const keyOf = new Map(d.requirements.map((r) => [r.id, r.subtaskKey ?? r.id]));
  // Fail closed, like the panel: the reason and controls may describe a restricted source, so they are shown only when
  // the requirement is on this page and its threat is shown in full.
  const reqOf = new Map(d.requirements.map((r) => [r.id, r]));
  const acceptanceShown = (a: Acceptance) => {
    const r = reqOf.get(a.requirementId);
    return r !== undefined && threatOf.has(r.threatId) && !redacted.has(r.threatId);
  };
  out.push(
    d.acceptances.length === 0
      ? '<p>No risk acceptances.</p>'
      : table(
          ['Requirement', 'Severity', 'Reason', 'Compensating controls', 'State', 'Expires'],
          d.acceptances.map((a) => {
            const shown = acceptanceShown(a);
            const reason = shown ? esc(a.reason) : '<em>Details in the Threatline panel.</em>';
            return [esc(keyOf.get(a.requirementId) ?? a.requirementId), esc(a.severity), reason, shown ? esc(a.controls) : '', esc(a.state), day(a.expiresAt)];
          }),
        ),
  );

  out.push('<h2>Revision history</h2>');
  out.push(table(['Revision', 'Date', 'Risk', 'Status'], d.history.map((h) => [String(h.revision), day(h.createdAt), String(h.riskScore), esc(h.status.replace(/_/g, ' '))])));

  out.push(OWNER_NOTES);
  out.push(d.ownerNotes || DEFAULT_OWNER_NOTES);
  return out.join('');
}

const KIND: Record<DiagramModel['nodes'][number]['kind'], string> = { external: 'External entity', process: 'Process', store: 'Data store' };

/**
 * The data-flow diagram as storage: Confluence storage cannot carry inline SVG safely, and an image attachment needs a
 * file-write scope Threatline does not ask for, so the diagram is three tables (elements, flows, trust boundaries).
 */
function renderDiagram(m: DiagramModel, partial: boolean, panelUrl: string): string[] {
  const name = new Map(m.nodes.map((n) => [n.id, n.name]));
  const boundary = new Map(m.boundaries.map((b) => [b.id, b.name]));
  const out = ['<h2>Data-flow diagram</h2>', `<p>${esc(m.summary)} The drawn diagram is in the ${link(panelUrl, 'Threatline panel')} (Diagram tab).</p>`];
  if (partial)
    out.push(macro('note', '<p>Parts of the architecture come from sources not everyone who can read this page can open, so only the elements its threats name are listed here.</p>'));
  out.push('<h3>Elements</h3>');
  out.push(
    table(
      ['Element', 'Type', 'Trust boundary', 'Open threats', 'Highest open severity'],
      m.nodes.map((n) => [esc(n.name), esc(KIND[n.kind]), esc(n.boundaryId ? (boundary.get(n.boundaryId) ?? '') : '—'), String(n.openCount), esc(n.maxSeverity ?? '—')]),
    ),
  );
  out.push('<h3>Data flows</h3>');
  out.push(
    m.edges.length === 0
      ? '<p>No data flows were extracted.</p>'
      : table(
          ['#', 'From', 'To', 'Data', 'Crosses a trust boundary'],
          m.edges.map((e) => [String(e.n), esc(name.get(e.from) ?? ''), esc(name.get(e.to) ?? ''), esc(e.data || '—'), e.crossesBoundary ? 'Yes' : 'No']),
        ),
  );
  out.push('<h3>Trust boundaries</h3>');
  const rows = [
    ...m.boundaries.map((b) => [esc(b.implied ? `${b.name} (implied)` : b.name), esc(b.nodeIds.map((id) => name.get(id) ?? '').join(', '))]),
    ...m.unplacedBoundaries.map((b) => [esc(b), 'Not tied to an element']),
  ];
  out.push(rows.length === 0 ? '<p>No trust boundaries were extracted.</p>' : table(['Trust boundary', 'Elements inside'], rows));
  return out;
}

const VOID = new Set(['br', 'hr', 'img', 'col', 'input', 'meta', 'link', 'area', 'base', 'wbr', 'source', 'track', 'param', 'embed']);

/** True when every opening tag has a matching close in order (enough to keep a broken fragment out of the page). */
function balanced(xml: string): boolean {
  const stack: string[] = [];
  const re = /<(\/?)([A-Za-z][\w:.-]*)(?:\s[^<>]*?)?(\/?)>|<!\[CDATA\[[\s\S]*?\]\]>|<!--[\s\S]*?-->/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(xml)) !== null) {
    if (!m[2]) continue;
    const [, closing, name, self] = m;
    if (self || VOID.has(name!.toLowerCase())) continue;
    if (closing) {
      if (stack.pop() !== name) return false;
    } else stack.push(name!);
  }
  return stack.length === 0 && !/<(?![A-Za-z/!])/.test(xml.replace(/<!\[CDATA\[[\s\S]*?\]\]>/g, ''));
}

/** The storage between `<h2>Owner notes</h2>` and the next `<h2>` (or the end), or the default text. */
export function extractOwnerNotes(storage: string): string {
  const at = storage.indexOf(OWNER_NOTES);
  if (at < 0) return DEFAULT_OWNER_NOTES;
  const rest = storage.slice(at + OWNER_NOTES.length);
  const next = rest.search(/<h2[\s>]/);
  const notes = (next < 0 ? rest : rest.slice(0, next)).trim();
  if (!notes || !balanced(notes)) return DEFAULT_OWNER_NOTES;
  return notes;
}
